def main():
    root = Path(__file__).resolve().parent.parent / "app" / "translations"
    root.mkdir(parents=True, exist_ok=True)

    en_keys = set(EN.keys())
    ur_keys = set(UR.keys())
    sd_keys = set(SD.keys())

    assert en_keys == ur_keys, f"Mismatch EN vs UR: {en_keys ^ ur_keys}"
    assert en_keys == sd_keys, f"Mismatch EN vs SD: {en_keys ^ sd_keys}"

    for lang, data in [("en", EN), ("ur", UR), ("sd", SD)]:
        filepath = root / f"{lang}.json"
        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"Wrote {len(data)} translation keys to {filepath}")

if __name__ == "__main__":
    main()
